import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from ipywidgets import interact_manual, Dropdown, IntRangeSlider, Checkbox, Layout
from IPython.display import display


# Widgets
season_widget = Dropdown(
    options=list(df['Season'].unique()) + ['All'],
    value='All',
    description='Season:',
    layout=Layout(width='200px')
)

category_widget = Dropdown(
    options=list(df['Category'].unique()) + ['All'],
    value='All',
    description='Category:',
    layout=Layout(width='200px')
)

location_widget = Dropdown(
    options=list(df['Location'].unique()) + ['All'],
    value='All',
    description='Location:',
    layout=Layout(width='200px')
)

age_widget = IntRangeSlider(
    value=[20, 40],
    min=int(df['Age'].min()),
    max=int(df['Age'].max()),
    step=1,
    description='Age Range:',
    continuous_update=False,
    layout=Layout(width='400px')
)

split_gender = Checkbox(
    value=False,
    description='Split by Gender',
    indent=False,
    layout=Layout(width='200px')
)

chart_type = Dropdown(
    options=['Bar', 'Pie'],
    value='Bar',
    description='Chart:',
    layout=Layout(width='200px')
)

# Function
@interact_manual(season=season_widget, category=category_widget, location=location_widget, age=age_widget, split_gender=split_gender, chart_type=chart_type)
def plot_sales(season, category, location, age, split_gender, chart_type):
    fc = df.copy()

    # Filter
    if season != 'All':
        fc = fc[fc['Season'] == season]
    if category != 'All':
        fc = fc[fc['Category'] == category]
    if location != 'All':
        fc = fc[fc['Location'] == location]
    fc = fc[(fc['Age'] >= age[0]) & (fc['Age'] <= age[1])]

    # ---- Show Table ----
    if split_gender:
        summary = fc.groupby('Gender')['Purchase Amount (USD)'].sum().reset_index().rename(columns={'Purchase Amount (USD)':'Total Sales (USD)'})
    else:
        summary = fc.groupby('Category')['Purchase Amount (USD)'].sum().reset_index().rename(columns={'Purchase Amount (USD)':'Total Sales (USD)'})

    print("Filtered Data Summary")
    display(summary)

    # ---- Show Chart ----
    if split_gender:
        gender_sales = summary.set_index('Gender')['Total Sales (USD)']

        if chart_type == 'Bar':
            gender_sales.plot(kind='bar', color=['#87CEFA','#F08080'], figsize=(6,4))
            plt.title("Sales by Gender")
            plt.ylabel("Total Sales (USD)")
            plt.xlabel("Gender")
            plt.show()

        elif chart_type == 'Pie':
            gender_sales.plot(kind='pie', autopct='%1.1f%%', figsize=(5,5), colors=['#87CEFA','#F08080'])
            plt.ylabel("")
            plt.title("Sales by Gender")
            plt.show()


    else:
        category_sales = summary.set_index('Category')['Total Sales (USD)']

        if chart_type == 'Bar':
            category_sales.plot(kind='bar', figsize=(8,5), color='lightgreen')
            plt.title("Total Sales by Category")
            plt.ylabel("Total Sales (USD)")
            plt.xticks(rotation=45)
            plt.show()

        elif chart_type == 'Pie':
            category_sales.plot(kind='pie', autopct='%1.1f%%', figsize=(6,6), colormap='Set3')
            plt.ylabel("")
            plt.title("Total Sales by Category")
            plt.show()
